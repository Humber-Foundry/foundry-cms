import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { createServer } from "vite";

const root = resolve(import.meta.dirname, "../../..");
const vite = await createServer({
  root,
  appType: "custom",
  server: { middlewareMode: true, hmr: false },
});

try {
  const { siteDefinitionSchema } = await vite.ssrLoadModule(
    "/packages/site-definition/src/index.ts",
  );
  const ajv = new Ajv2020({
    allErrors: true,
    code: { esm: true, source: true },
  });
  const validate = ajv.compile(siteDefinitionSchema);
  const generatedValidator = standaloneCode(ajv, validate).replace(
    'const func1 = require("ajv/dist/runtime/ucs2length").default;',
    "const func1 = (value) => [...value].length;",
  );
  if (generatedValidator.includes("require(")) {
    throw new Error("standalone_site_validator_has_runtime_import");
  }
  const generated = [
    "// Generated by packages/site-definition/scripts/generate-validator.mjs.",
    "// Do not edit by hand; regenerate after changing siteDefinitionSchema.",
    generatedValidator,
    "",
  ].join("\n");
  const output = resolve(
    root,
    "packages/site-definition/src/site-definition-validator.mjs",
  );
  if (process.argv.includes("--check")) {
    const current = await readFile(output, "utf8");
    if (current !== generated) {
      throw new Error(
        "site_definition_validator_out_of_date: run npm run generate:site-validator",
      );
    }
    console.log("Verified the generated Site Definition validator is current.");
  } else {
    await writeFile(output, generated, "utf8");
  }
} finally {
  await vite.close();
}
